const WHITE = rgba(0xffffff);

const SHEET = FONT_COLS * BOX.w;

export function fontSheet(): Grid {
  const grid = createGrid(SHEET);

  for (let code = FIRST_CODE; code <= LAST_CODE; code += 1) {
    const character = String.fromCharCode(code);
    const art = GLYPHS[character];
    if (art === undefined) throw new Error(`font: nothing drawn for "${character}" (${code})`);

    const slot = code - FIRST_CODE;
    const left = (slot % FONT_COLS) * BOX.w;
    const top = Math.floor(slot / FONT_COLS) * BOX.h;

    const rows = art === '' ? [] : art.split('/');
    rows.forEach((row, y) => {
      if (row.length !== GLYPH.w) {
        throw new Error(`font: "${character}" row ${y} is ${row.length} cells, expected ${GLYPH.w}`);
      }
      if (y >= BOX.h) throw new Error(`font: "${character}" is taller than the box`);
      for (let x = 0; x < GLYPH.w; x += 1) {
        if (row[x] === '#') put(grid, left + x, top + y, WHITE);
      }
    });
  }

  return grid;
}

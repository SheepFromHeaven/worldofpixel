/** Square, so one grid holds them all: four across and four down, in declaration order. */
const SHEET = ICON_CELLS * ICON_COLS;

export function iconSheet(): Grid {
  const grid = createGrid(SHEET);

  ICON_NAMES.forEach((name, slot) => {
    const rows = ICONS[name];
    if (rows.length !== ICON_CELLS) {
      throw new Error(`icon ${name}: ${rows.length} rows, expected ${ICON_CELLS}`);
    }
    const left = (slot % ICON_COLS) * ICON_CELLS;
    const top = Math.floor(slot / ICON_COLS) * ICON_CELLS;
    paint(grid, left, top, rows, ICON_CELLS);
  });

  return grid;
}

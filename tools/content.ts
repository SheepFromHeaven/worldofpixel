import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const base = resolve(fileURLToPath(new URL('..', import.meta.url)), 'src');

const root = resolve(base, 'content');

export const KINDS = [
  { kind: 'items', defs: 'ITEM_DEFS', arts: 'ITEM_ART_LIST' },
  { kind: 'stations', defs: 'STATION_DEFS', arts: 'STATION_ART_LIST' },
  { kind: 'blocks', defs: 'BLOCK_DEFS', arts: 'BLOCK_ART_LIST' },
] as const;

interface Folder {
  readonly name: string;
  readonly path: string;
  readonly order: number;
  readonly art: boolean;
}

const roots = (kind: string): string[] => {
  const found = [resolve(root, kind)];
  const modules = resolve(base, 'modules');
  for (const module of readdirSync(modules).sort()) {
    const directory = resolve(modules, module, 'content', kind);
    if (existsSync(directory)) found.push(directory);
  }
  return found;
};

const folders = (kind: string): Folder[] => {
  const found: Folder[] = [];
  for (const directory of roots(kind)) {
    for (const name of readdirSync(directory)) {
      if (!statSync(resolve(directory, name)).isDirectory()) continue;
      const index = resolve(directory, name, 'index.ts');
      if (!existsSync(index)) continue;
      const order = /export const order = (\d+);/.exec(readFileSync(index, 'utf8'));
      if (!order) throw new Error(`${kind}/${name}/index.ts has no order`);
      found.push({ name, path: resolve(directory, name), order: Number(order[1]), art: existsSync(resolve(directory, name, 'art.ts')) });
    }
  }
  const sorted = found.sort((a, b) => a.order - b.order || (a.name < b.name ? -1 : 1));
  for (let i = 1; i < sorted.length; i += 1) if (sorted[i]!.order === sorted[i - 1]!.order) throw new Error(`${kind}: ${sorted[i - 1]!.name} and ${sorted[i]!.name} share order ${sorted[i]!.order}`);
  return sorted;
};

const researchFiles = (): string[] => {
  const modules = resolve(base, 'modules');
  return readdirSync(modules).sort().map((module) => resolve(modules, module, 'research.ts')).filter((file) => existsSync(file));
};

const head = '// generated by tools/content.ts, do not edit\n';

const writeResearch = (): void => {
  const files = researchFiles();
  const dir = resolve(root, 'research');
  const imports = files.map((file, at) => `import { RESEARCH_ENTRIES as list${at} } from '${relative(dir, file).replaceAll('\\', '/').replace(/^(?!\.)/, './')}';`).join('\n');
  writeFileSync(resolve(dir, 'manifest.generated.ts'), `${head}import type { ResearchDef } from './definition.ts';\n${imports}\n\nexport const RESEARCH_LISTS: readonly (readonly ResearchDef[])[] = [${files.map((_, at) => `list${at}`).join(', ')}];\n`);
};

export const write = (): void => {
  writeResearch();
  for (const { kind, defs, arts } of KINDS) {
    const list = folders(kind);
    const from = (f: Folder, file: string): string => {
      const path = relative(resolve(root, kind), resolve(f.path, file)).replaceAll('\\', '/');
      return path.startsWith('.') ? path : `./${path}`;
    };
    const type = kind === 'items' ? 'ItemDef' : 'StationDef';
    const typeFrom = kind === 'items' ? '../items/definition.ts' : '../stations/definition.ts';
    const imports = list.map((f) => `import ${f.name} from '${from(f, 'index.ts')}';`).join('\n');
    writeFileSync(resolve(root, kind, 'manifest.generated.ts'), `${head}import type { ${type} } from '${typeFrom}';\n${imports}\n\nexport const ${defs}: readonly ${type}[] = [${list.map((f) => f.name).join(', ')}];\n`);
    const withArt = list.filter((f) => f.art);
    const artImports = withArt.map((f) => `import { art as ${f.name}Art } from '${from(f, 'art.ts')}';`).join('\n');
    if (kind === 'items') {
      const defImports = withArt.map((f) => `import ${f.name} from '${from(f, 'index.ts')}';`).join('\n');
      const pairs = withArt.map((f) => `[${f.name}.art, ${f.name}Art]`).join(', ');
      writeFileSync(resolve(root, kind, 'art.manifest.generated.ts'), `${head}import type { Art } from '../art.ts';\n${defImports}\n${artImports}\n\nexport const ${arts}: readonly (readonly [string, Art])[] = [${pairs}];\n`);
    } else {
      const entries = withArt.map((f) => `${f.name}Art`).join(', ');
      writeFileSync(resolve(root, kind, 'art.manifest.generated.ts'), `${head}import type { Art } from '../art.ts';\n${artImports}\n\nexport const ${arts}: readonly Art[] = [${entries}];\n`);
    }
  }
};

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) write();
